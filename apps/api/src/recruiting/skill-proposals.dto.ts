import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import { IsIn, IsInt, IsOptional, IsString, MaxLength, Min, MinLength, Matches } from "class-validator";

export class ReviewSkillProposalDto {
  @ApiProperty({ enum: ["approved", "rejected"] })
  @IsIn(["approved", "rejected"]) decision!: "approved" | "rejected";

  @ApiProperty({ minimum: 0 })
  @IsInt() @Min(0) expectedVersion!: number;

  @ApiProperty({ minLength: 8, maxLength: 1000 })
  @IsString() @MinLength(8) @MaxLength(1000) reason!: string;

  @ApiPropertyOptional({ description: "Optional human-reviewed alias literal in the resume excerpt; never generated by the model automatically" })
  @IsOptional() @IsString() @MaxLength(200) @Matches(/^[^<>]+$/)
  reviewedAlias?: string;
}

export class SkillProposalDto {
  @ApiProperty() id!: string;
  @ApiProperty() skillKey!: string;
  @ApiProperty() claimText!: string;
  @ApiProperty() startChar!: number;
  @ApiProperty() endChar!: number;
  @ApiProperty() confidence!: number;
  @ApiProperty() reviewState!: string;
  @ApiProperty() reviewVersion!: number;
  @ApiProperty() sourceTextSha256!: string;
  @ApiProperty() provider!: string;
  @ApiProperty() model!: string;
}

export class SkillProposalResponseDto {
  @ApiProperty({ enum: ["ok", "disabled", "unavailable", "source_too_large", "no_taxonomy"] })
  status!: string;
  @ApiProperty() persistedCount!: number;
  @ApiProperty({ type: [SkillProposalDto] }) proposals!: SkillProposalDto[];
}

export class ReviewedSkillProposalDto {
  @ApiProperty() proposalId!: string;
  @ApiProperty() reviewState!: string;
  @ApiProperty() reviewVersion!: number;
  @ApiProperty() reviewerUserId!: string;
  @ApiProperty() reviewedAt!: string;
}
